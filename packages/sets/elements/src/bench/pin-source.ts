/**
 * How a live kit file becomes its calibration copy — ONE function, shared by
 * the generator (`scripts/refresh-calibration.ts`) and the drift check
 * (`pinned.ts`), which re-pins the live file and compares. Comparing forward
 * rather than undoing the rename means the check can never disagree with the
 * generator. Kept free of side effects: the generator imports it while the
 * snapshot it is about to replace is deleted.
 */
import fs from 'node:fs';
import path from 'node:path';
import { COMMON_SKILL_FILES, COMMON_SKILLS_DIR } from '@pimpampum/set-common/bench';

export const PIN = '@cal';

/**
 * The live file of a kit: this set's own `skills/` dir, unless the kit is one
 * set-common holds — paired BY ID, since a shared kit's file is named for its
 * skill (Esgrima) and its copy keeps whatever name the last refresh gave it.
 */
export function liveKitFile(id: string, file: string, live: string, common = COMMON_SKILLS_DIR): string {
  const shared = COMMON_SKILL_FILES[id];
  return shared ? path.join(common, shared) : path.join(live, file);
}

/** Every live kit file the snapshot should hold: this set's own, plus the
 *  set-common kits it fields. */
export function liveKitFiles(live: string, fielded: (id: string) => boolean, common = COMMON_SKILLS_DIR): string[] {
  return [
    ...fs.readdirSync(live).filter(f => f.endsWith('.ts')).sort().map(f => path.join(live, f)),
    ...Object.entries(COMMON_SKILL_FILES).filter(([id]) => fielded(id)).map(([, f]) => path.join(common, f)),
  ];
}

export const PIN_HEADER = '// PINNED CALIBRATION COPY — generated by scripts/refresh-calibration.ts from\n'
  + '// src/players/skills/. Do not edit: edit the live kit, then refresh when the\n'
  + '// baselines should follow it.\n';

export interface PinnableSkill { id: string; actions: { id: string }[]; effects?: Record<string, unknown> }

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Every string literal naming the kit's skill id, a card id or one of its own
 * effect types gets `@cal`; so does an effect type written as a bare object key
 * (`effects: { enter_rage: … }`), which is how the effect maps are written.
 * Relative imports are re-rooted from `players/skills/` to `bench/calibration-kits/`.
 */
export function pinSource(src: string, skill: PinnableSkill): string {
  let out = src.replace(/from '\.\.\//g, "from '../../players/");
  for (const n of new Set([skill.id, ...skill.actions.map(a => a.id), ...Object.keys(skill.effects ?? {})])) {
    out = out.replace(new RegExp(`(['"])${escape(n)}\\1`, 'g'), `$1${n}${PIN}$1`);
  }
  for (const n of Object.keys(skill.effects ?? {})) {
    if (/^[A-Za-z_$][\w$]*$/.test(n)) {
      out = out.replace(new RegExp(`(^|[\\s{,])${escape(n)}(\\s*:)`, 'gm'), `$1'${n}${PIN}'$2`);
    }
  }
  return PIN_HEADER + out;
}
